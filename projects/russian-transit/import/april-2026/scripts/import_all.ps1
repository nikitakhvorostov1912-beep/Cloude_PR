  $id = Get-Random -Minimum 100 -Maximum 999999
  $body = @{ jsonrpc='2.0'; id=$id; method='tools/call'; params=@{ name='execute_code'; arguments=@{ code=$code } } } | ConvertTo-Json -Depth 10 -Compress
  try {
    $resp = Invoke-WebRequest -Uri 'http://127.0.0.1:6010/mcp' -Method Post -Body $body -ContentType 'application/json' `
      -Headers @{ Accept='application/json, text/event-stream'; 'Mcp-Session-Id'=$sid } -UseBasicParsing -TimeoutSec 600
    $txt = ($resp.Content -split "`r?`n" | Where-Object { $_ -match '^data:\s' } | ForEach-Object { $_ -replace '^data:\s?','' }) -join "`n"
    $j = $txt | ConvertFrom-Json
    $inner = $j.result.content[0].text | ConvertFrom-Json
    if ($inner.success) {
      $data = $inner.data -replace '\\n', "`n" -replace '\\"', '"'
      $m = [regex]::Match($data, 'Создано=(\d+)\s+Пропущено=(\d+)\s+Ошибок=(\d+)')
      if ($m.Success) {
        $c = [int]$m.Groups[1].Value
        $sk = [int]$m.Groups[2].Value
        $er = [int]$m.Groups[3].Value
        $created += $c; $skipped += $sk; $errors += $er
        $line = ("Batch {0,4}-{1,4}: создано={2,3} пропущено={3,2} ошибок={4,2} | ИТОГО созд={5} пропущ={6} ош={7}" -f $start, $end, $c, $sk, $er, $created, $skipped, $errors)
        Write-Host $line
        $line | Out-File $logFile -Append
        if ($er -gt 0) { $data | Out-File "C:\CLOUDE_PR\tmp\err_$start.txt" -Encoding UTF8 }
      } else {
        Write-Host "Batch $start unparsed"
      }
    } else {
      Write-Host "Batch $start FAILED: $($inner.error)"
      "Batch $start FAILED: $($inner.error)" | Out-File $logFile -Append
    }
  } catch {
    Write-Host "Batch $start EXC: $($_.Exception.Message)"
    "Batch $start EXC: $($_.Exception.Message)" | Out-File $logFile -Append
    Start-Sleep -Seconds 5
  }
  $start = $start + $BatchSize
}

